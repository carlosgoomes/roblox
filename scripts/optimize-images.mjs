import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const output=resolve(root,'public/assets/optimized');
mkdirSync(output,{recursive:true});
const generated=new Set();
function image(source,name,width,quality=86){
  const bytes=execFileSync('magick',[resolve(root,source),...(width?['-resize',width+'x']:[]),'-strip','-quality',String(quality),'webp:-'],{maxBuffer:16*1024*1024});
  const hash=createHash('sha256').update(bytes).digest('hex').slice(0,10);
  const filename=name+'-'+hash+'.webp';generated.add(filename);
  writeFileSync(resolve(output,filename),bytes);
  return {url:'/assets/optimized/'+filename,bytes:bytes.length};
}
const sizes={
  hero:'(max-width: 767px) calc(100vw - 32px), (max-width: 900px) calc(100vw - 64px), (max-width: 1304px) calc(63vw - 54px), 800px',
  promotion:'(max-width: 767px) calc(100vw - 34px), (max-width: 900px) 620px, (max-width: 1304px) calc(37vw - 32px), 480px'
};
const assets={banners:{},products:{}};
for(const [name,source] of [['hero','realbux-banner'],['promotion','realbux-promo-75']]){
  const variants=[480,800,1200,1600].map(width=>({width,...image('public/assets/'+source+'.png',source+'-'+width,width,84)}));
  assets.banners[name]={src:variants.find(v=>v.width===800).url,srcset:variants.map(v=>v.url+' '+v.width+'w').join(', '),sizes:sizes[name],variants};
}
for(const name of ['fruits','equipment'])assets.products[name]=image('public/assets/products/'+name+'-atlas.png',name+'-atlas',null).url;
writeFileSync(resolve(root,'public/optimized-assets.js'),'// Generated by npm run assets:optimize; keep source artwork unchanged.\nexport const optimizedAssets = '+JSON.stringify(assets,null,2)+';\n');
let html=readFileSync(resolve(root,'public/index.html'),'utf8');
const hints='<!-- Performance image hints -->\n'+Object.values(assets.banners).map(b=>'  <link rel="preload" as="image" href="'+b.src+'" imagesrcset="'+b.srcset+'" imagesizes="'+b.sizes+'" fetchpriority="high">').join('\n')+'\n  <!-- End performance image hints -->';
if(html.includes('<!-- Performance image hints -->'))html=html.replace(/<!-- Performance image hints -->[\s\S]*?<!-- End performance image hints -->/,hints);
else html=html.replace('  <link rel="icon"','  '+hints+'\n  <link rel="icon"');
writeFileSync(resolve(root,'public/index.html'),html);
console.log(JSON.stringify({generated:generated.size,banner800Bytes:Object.fromEntries(Object.entries(assets.banners).map(([name,b])=>[name,b.variants.find(v=>v.width===800).bytes]))}));
